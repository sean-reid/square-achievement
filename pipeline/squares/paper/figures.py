"""Write the paper's board diagrams as TikZ, from the rule's own play.

Each figure is drawn from positions the rule computes, so the diagrams
cannot drift from the code: the basic line and the longest line are
replayed against an opponent who blocks, the second-move diagram reads
the rule's second move, and the latent-corner figure asserts its pair's
corner.

python3 -m squares.paper.figures   writes paper/fig-*.tex
"""

from ..latent import farm_relation
from ..paths import REPO
from ..plus.measure import line_with_key
from ..plus.rule import OPENING, abstract_of, my_threats, second_move

PAPER = REPO / "paper"
HEAD = "% Generated by python3 -m squares.paper.figures; do not edit.\n"


def board(black, white, threats, scale=0.5, label=None):
    """A 6 x 6 board with our stones black, the opponent's white, and
    threat cells dashed."""
    out = [f"\\begin{{tikzpicture}}[scale={scale}]", "  \\draw[gray!60] (0,0) grid (6,-6);"]
    if black:
        cells = ", ".join(f"{r}/{c}" for r, c in black)
        out.append("  \\foreach \\r/\\c in {" + cells + "}")
        out.append("    \\fill[black] (\\c+0.5,-\\r-0.5) circle (0.26);")
    if white:
        cells = ", ".join(f"{r}/{c}" for r, c in white)
        out.append("  \\foreach \\r/\\c in {" + cells + "}")
        out.append("    \\draw[thick] (\\c+0.5,-\\r-0.5) circle (0.26);")
    for r, c in threats:
        out.append(f"  \\draw[thick,dashed] ({c + 0.5},{-r - 0.5}) circle (0.28);")
    if label:
        out.append(f"  \\node at (3,-6.6) {{\\small {label}}};")
    out.append("\\end{tikzpicture}")
    return "\n".join(out)


def play(o1, o2):
    """The positions along the rule's line against o1, o2 with an opponent
    who blocks: a list of (our stones, their stones, our threats) after
    each of our moves, and the line's tempo count."""
    x2 = second_move(o1)
    a = abstract_of([OPENING, x2], [o1, o2], o1, o2)
    line, tempo, _ = line_with_key(a)
    p1, p2 = [OPENING, x2], [o1, o2]
    states = []
    for m in line:
        p1 = p1 + [m]
        th = my_threats(p1, p1 + p2)
        states.append((list(p1), list(p2), th))
        if len(th) >= 2:
            break
        p2 = p2 + [th[0]]
    return states, tempo


def fmt(c):
    return f"$({c[0]},{c[1]})$"


def panels(states, labels):
    """Side-by-side boards, one per state, each with its label."""
    return "\n\\hspace{1em}\n".join(
        board(p1, p2, th, label=label)
        for (p1, p2, th), label in zip(states, labels, strict=True)
    )


def fig_anatomy():
    def plus(centre, side, square):
        r, k = centre
        arms = [(r - side, k), (r + side, k), (r, k - side), (r, k + side)]
        diags = [
            (r - side, k - side),
            (r - side, k + side),
            (r + side, k - side),
            (r + side, k + side),
        ]
        (sr, sc), s = square
        return "\n".join(
            [
                "\\begin{tikzpicture}[scale=0.55]",
                "  \\draw[gray!60] (0,0) grid (6,-6);",
                f"  \\node at ({k + 0.5},{-r - 0.5}) {{$c$}};",
                "  \\foreach \\r/\\c in {"
                + ", ".join(f"{a}/{b}" for a, b in arms)
                + "} \\node at (\\c+0.5,-\\r-0.5) {$a$};",
                "  \\foreach \\r/\\c in {"
                + ", ".join(f"{a}/{b}" for a, b in diags)
                + "} \\node at (\\c+0.5,-\\r-0.5) {$d$};",
                f"  \\draw[thick,dashed] ({sc + 0.08},{-sr - 0.08}) rectangle "
                f"({sc + s + 1 - 0.08},{-sr - s - 1 + 0.08});",
                "\\end{tikzpicture}",
            ]
        )

    return plus((2, 2), 1, ((1, 1), 1)) + "\n\\hspace{2em}\n" + plus((3, 2), 2, ((1, 0), 2))


def fig_second():
    marks = {(2, 1): "a", (2, 3): "b", (1, 2): "c"}
    cells = []
    for r in range(6):
        for c in range(6):
            if (r, c) == OPENING:
                continue
            x2 = second_move((r, c))
            if x2 != (3, 2):
                cells.append(f"{r}/{c}/{marks[x2]}")
    return "\n".join(
        [
            "\\begin{tikzpicture}[scale=0.7]",
            "  \\draw[gray!60] (0,0) grid (6,-6);",
            "  \\fill[black] (2.5,-2.5) circle (0.26);",
            "  \\foreach \\r/\\c/\\t in {" + ", ".join(cells) + "}",
            "    \\node at (\\c+0.5,-\\r-0.5) {$\\t$};",
            "\\end{tikzpicture}",
        ]
    )


def fig_basic():
    states, tempo = play((0, 0), (4, 4))
    assert tempo == 0 and len(states) == 3
    labels = ["after " + fmt(states[0][0][-1])] + [
        "after " + fmt(p2[-1]) + ", " + fmt(p1[-1]) for p1, p2, _ in states[1:]
    ]
    return panels(states, labels)


def fig_tempo():
    states, tempo = play((0, 0), (3, 1))
    assert tempo == 2
    labels = [
        "tempo move " + fmt(states[0][0][-1]),
        "tempo move " + fmt(states[1][0][-1]),
        "first arm " + fmt(states[2][0][-1]),
    ]
    return panels(states[:3], labels)


def fig_longest():
    states, _ = play((0, 0), (3, 1))
    p1, p2, th = states[-1]
    assert len(th) == 2 and len(p1) == 8
    return board(p1, p2, th, scale=0.55)


def fig_latent():
    o1, o2 = (0, 17), (14, 3)
    assert farm_relation(o1, o2) == ("farm", (0, 3))
    return "\n".join(
        [
            "\\begin{tikzpicture}[scale=0.3]",
            "  \\fill[gray!25] (0,0) rectangle (6,-6);",
            "  \\draw[gray!60] (0,0) grid (18,-18);",
            "  \\draw[thick] (0,0) rectangle (17,-17);",
            "  \\draw[thick,dashed] (3.5,-0.5) rectangle (17.5,-14.5);",
            f"  \\foreach \\r/\\c in {{{o1[0]}/{o1[1]}, {o2[0]}/{o2[1]}}}",
            "    \\draw[thick] (\\c+0.5,-\\r-0.5) circle (0.3);",
            "  \\draw[thick,dashed] (3.5,-0.5) circle (0.38);",
            "  \\draw[thick,dashed] (17.5,-14.5) circle (0.38);",
            "  \\node[above=1pt] at (3.5,-0.1) {$b$};",
            "  \\node[above=1pt] at (17.5,-0.1) {$o_1$};",
            "  \\node[left=2pt] at (3.1,-14.5) {$o_2$};",
            "  \\node[right=2pt] at (18.0,-14.5) {$z$};",
            "\\end{tikzpicture}",
        ]
    )


FIGURES = {
    "fig-anatomy": fig_anatomy,
    "fig-second": fig_second,
    "fig-basic": fig_basic,
    "fig-tempo": fig_tempo,
    "fig-longest": fig_longest,
    "fig-latent": fig_latent,
}


def build_figures():
    return {name: HEAD + fn() + "\n" for name, fn in FIGURES.items()}


def main():
    for name, text in build_figures().items():
        path = PAPER / f"{name}.tex"
        path.write_text(text)
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
