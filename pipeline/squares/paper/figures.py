"""Write the paper's board diagrams as TikZ, from the rule's own play.

Each figure is drawn from positions the rule computes, so the diagrams
cannot drift from the code: the basic line and the longest line are
replayed against an opponent who blocks, the second-move diagram reads
the rule's second move, and the hidden-corner figure asserts its pair's
corner.

python3 -m squares.paper.figures   writes paper/fig-*.tex
"""

from ..latent import farm_relation
from ..paths import REPO
from ..plus.measure import line_with_key
from ..plus.rule import OPENING, abstract_of, my_threats, second_move

PAPER = REPO / "paper"
HEAD = "% Generated by python3 -m squares.paper.figures; do not edit.\n"

SMALL, LARGE = 0.55, 0.3
STONE, MARK = 0.26, 0.28
BIG = 0.42
GRID = "gray!60"
REGION = "gray!25"


def open_board(n, scale, options=""):
    opts = f"scale={scale}" + (f",{options}" if options else "")
    return [f"\\begin{{tikzpicture}}[{opts}]", f"  \\draw[{GRID}] (0,0) grid ({n},{-n});"]


def stones(cells, colour, r):
    if not cells:
        return []
    listed = ", ".join(f"{a}/{b}" for a, b in cells)
    return [
        "  \\foreach \\r/\\c in {" + listed + "}",
        f"    \\filldraw[fill={colour},thick] (\\c+0.5,-\\r-0.5) circle ({r});",
    ]


def mark(cell, r):
    return f"  \\draw[thick,dashed] ({cell[1] + 0.5},{-cell[0] - 0.5}) circle ({r});"


def dashed_square(corner, side):
    """The square whose top-left corner cell is corner, through cell centres."""
    r, c = corner
    return (
        f"  \\draw[thick,dashed] ({c + 0.5},{-r - 0.5}) rectangle "
        f"({c + side + 0.5},{-r - side - 0.5});"
    )


def label(text, cell, side, r=BIG):
    """A label against a marker of radius r on the given side of cell."""
    x, y = cell[1] + 0.5, -cell[0] - 0.5
    gap = r + 0.12
    anchor, (px, py) = {
        "right": ("west", (x + gap, y)),
        "left": ("east", (x - gap, y)),
        "above": ("south", (x, y + gap)),
        "below": ("north", (x, y - gap)),
    }[side]
    return f"  \\node[anchor={anchor},inner sep=1pt] at ({px:g},{py:g}) {{{text}}};"


def board(black, white, threats, n=6, label=None):
    """An n x n board with our stones black, the opponent's white, and
    threat cells dashed."""
    out = open_board(n, SMALL)
    out += stones(black, "black", STONE)
    out += stones(white, "white", STONE)
    out += [mark(t, MARK) for t in threats]
    if label:
        out.append(f"  \\node at ({n / 2:g},{-n - 0.6}) {{\\small {label}}};")
    out.append("\\end{tikzpicture}")
    return "\n".join(out)


def large_board(n, base=17, region=6, options=""):
    """An n x n board with the region shaded, the base board outlined,
    and a heavier border."""
    out = open_board(n, LARGE, options)
    out.insert(1, f"  \\fill[{REGION}] (0,0) rectangle ({region},{-region});")
    out.append(f"  \\draw[semithick] (0,0) rectangle ({base},{-base});")
    out.append(f"  \\draw[very thick] (0,0) rectangle ({n},{-n});")
    return out


def play(o1, o2):
    """The positions along the rule's line against o1, o2 with an opponent
    who blocks: a list of (our stones, their stones, our threats) after
    each of our moves, and the line's tempo count."""
    x2 = second_move(o1)
    a = abstract_of([OPENING, x2], [o1, o2], o1, o2)
    line, tempo, _ = line_with_key(a)
    p1, p2 = [OPENING, x2], [o1, o2]
    states = []
    for m in line:
        p1 = p1 + [m]
        th = my_threats(p1, p1 + p2)
        states.append((list(p1), list(p2), th))
        if len(th) >= 2:
            break
        p2 = p2 + [th[0]]
    return states, tempo


def ply_labels(states):
    """Panel labels by ply, as in the paper's game table: the first
    panel shows our move, each later one the block and our next move."""
    out = []
    for i, (p1, _, _) in enumerate(states):
        ply = 2 * len(p1) - 1
        out.append(f"ply {ply}" if i == 0 else f"plies {ply - 1}--{ply}")
    return out


def panels(states, labels):
    """Side-by-side boards, one per state, each with its label."""
    return "\n\\hspace{1em}\n".join(
        board(p1, p2, th, label=label)
        for (p1, p2, th), label in zip(states, labels, strict=True)
    )


def fig_anatomy():
    def plus(centre, side, square):
        r, k = centre
        arms = [(r - side, k), (r + side, k), (r, k - side), (r, k + side)]
        diags = [
            (r - side, k - side),
            (r - side, k + side),
            (r + side, k - side),
            (r + side, k + side),
        ]
        (sr, sc), s = square
        return "\n".join(
            open_board(6, SMALL)
            + [
                f"  \\node at ({k + 0.5},{-r - 0.5}) {{$c$}};",
                "  \\foreach \\r/\\c in {"
                + ", ".join(f"{a}/{b}" for a, b in arms)
                + "} \\node at (\\c+0.5,-\\r-0.5) {$a$};",
                "  \\foreach \\r/\\c in {"
                + ", ".join(f"{a}/{b}" for a, b in diags)
                + "} \\node at (\\c+0.5,-\\r-0.5) {$d$};",
                f"  \\draw[thick,dashed] ({sc + 0.08},{-sr - 0.08}) rectangle "
                f"({sc + s + 1 - 0.08},{-sr - s - 1 + 0.08});",
                "\\end{tikzpicture}",
            ]
        )

    return plus((2, 2), 1, ((1, 1), 1)) + "\n\\hspace{2em}\n" + plus((3, 2), 2, ((1, 0), 2))


def fig_second():
    marks = {(2, 1): "1", (2, 3): "2", (1, 2): "3"}
    cells = []
    for r in range(6):
        for c in range(6):
            if (r, c) == OPENING:
                continue
            x2 = second_move((r, c))
            if x2 != (3, 2):
                cells.append(f"{r}/{c}/{marks[x2]}")
    return "\n".join(
        open_board(6, SMALL)
        + stones([OPENING], "black", STONE)
        + [
            "  \\foreach \\r/\\c/\\t in {" + ", ".join(cells) + "}",
            "    \\node at (\\c+0.5,-\\r-0.5) {$\\t$};",
            "\\end{tikzpicture}",
        ]
    )


def fig_basic():
    states, tempo = play((0, 0), (4, 4))
    assert tempo == 0 and len(states) == 3
    assert [p1[-1] for p1, _, _ in states] == [(2, 1), (1, 2), (2, 3)]
    return panels(states, ply_labels(states))


def fig_tempo():
    states, tempo = play((0, 0), (3, 1))
    assert tempo == 2
    assert [p1[-1] for p1, _, _ in states[:3]] == [(3, 3), (4, 3), (3, 4)]
    return panels(states[:3], ply_labels(states[:3]))


def fig_longest():
    states, _ = play((0, 0), (3, 1))
    p1, p2, th = states[-1]
    assert len(th) == 2 and len(p1) == 8
    return board(p1, p2, th)


def fig_latent():
    o1, o2 = (0, 17), (14, 3)
    b = (0, 3)
    assert farm_relation(o1, o2) == ("farm", b)
    z = (o2[0], o1[1])
    return "\n".join(
        large_board(18)
        + [dashed_square(b, o1[1] - b[1])]
        + stones([o1, o2], "white", BIG)
        + [
            mark(b, BIG),
            mark(z, BIG),
            label("$b$", b, "above"),
            label("$o_1$", o1, "above"),
            label("$o_2$", o2, "left"),
            label("$z$", z, "right"),
            "\\end{tikzpicture}",
        ]
    )


def fig_anchors():
    """The anchor board: the region, the base board, the two stand-ins,
    and one far pair replaced by its anchors, with the hidden square
    they share."""
    h = (2, 3)
    o1, o2 = (h[0] + 17, h[1] + 17), (h[0] + 17, h[1])
    assert farm_relation(o1, o2) == ("farm", h)
    assert farm_relation((22, 22), (22, 21)) is None
    s = 17
    return "\n".join(
        [
            "\\begin{tikzpicture}[scale=0.26]",
            "  \\fill[gray!25] (0,0) rectangle (6,-6);",
            "  \\draw[gray!60] (0,0) grid (23,-23);",
            "  \\draw[thick] (0,0) rectangle (17,-17);",
            "  \\draw[thick] (0,0) rectangle (23,-23);",
            f"  \\draw[thick,dashed] ({h[1] + 0.5},{-h[0] - 0.5}) rectangle "
            f"({h[1] + s + 0.5},{-h[0] - s - 0.5});",
            f"  \\foreach \\r/\\c in {{{o1[0]}/{o1[1]}, {o2[0]}/{o2[1]}}}",
            "    \\draw[thick] (\\c+0.5,-\\r-0.5) circle (0.42);",
            f"  \\draw[thick,dashed] ({h[1] + 0.5},{-h[0] - 0.5}) circle (0.5);",
            "  \\foreach \\r/\\c in {22/22, 22/21}",
            "    \\fill[gray!70] (\\c+0.5,-\\r-0.5) circle (0.42);",
            f"  \\node[above left=0pt] at ({h[1] + 0.3},{-h[0] - 0.2}) {{$b$}};",
            f"  \\node[right=3pt] at (23.2,{-o1[0] - 0.5}) {{$o_1'$}};",
            f"  \\node[left=3pt] at (-0.2,{-o2[0] - 0.5}) {{$o_2'$}};",
            "  \\node[below=2pt] at (21.5,-23.0) {\\small stand-ins};",
            "  \\node at (14.5,-15.5) {$\\Board_{17}$};",
            "  \\node[left=3pt] at (-0.2,-3) {$\\Board_6$};",
            "\\end{tikzpicture}",
        ]
    )


FIGURES = {
    "fig-anatomy": fig_anatomy,
    "fig-second": fig_second,
    "fig-basic": fig_basic,
    "fig-tempo": fig_tempo,
    "fig-longest": fig_longest,
    "fig-latent": fig_latent,
    "fig-anchors": fig_anchors,
}


def build_figures():
    return {name: HEAD + fn() + "\n" for name, fn in FIGURES.items()}


def main():
    for name, text in build_figures().items():
        path = PAPER / f"{name}.tex"
        path.write_text(text)
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
